import fs from 'node:fs'
import path from 'node:path'

import { expect, test } from '@jest/globals'
import { temporaryDirectory } from 'tempy'

import { readVersionsByPackageNames } from '../src/import/lockfileVersions.js'

test('reads the versions of a package whose name is an Object.prototype key', async () => {
  const dir = temporaryDirectory()
  fs.writeFileSync(path.join(dir, 'package-lock.json'), JSON.stringify({
    lockfileVersion: 1,
    dependencies: {
      constructor: { version: '1.0.0' },
    },
  }))

  const versionsByPackageNames = await readVersionsByPackageNames(dir)

  expect(Array.from(versionsByPackageNames['constructor'])).toStrictEqual(['1.0.0'])
})

test('does not misclassify Yarn v1 lockfiles mentioning __metadata package names as Yarn Berry', async () => {
  const dir = temporaryDirectory()
  fs.writeFileSync(path.join(dir, 'yarn.lock'), `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1
# __metadata:

"__metadata-helper@file:../meta":
  version "0.0.0"

"__metadata@1.0.0":
  version "1.0.0"

pkg-__metadata@^2.0.0:
  version "2.0.0"
  dependencies:
    "__metadata-helper" "file:../meta"
    "__metadata" "1.0.0"
`)

  const versionsByPackageNames = await readVersionsByPackageNames(dir)

  expect(toSortedArrays(versionsByPackageNames)).toStrictEqual({
    __metadata: ['1.0.0'],
    '__metadata-helper': ['0.0.0'],
    'pkg-__metadata': ['2.0.0'],
  })
})

test.each([
  '\uFEFF__metadata:\n  version: 6\n"foo@npm:1.0.0":\n  version: 1.0.0\n',
  '"__metadata":\r\n  version: 6\r\n"foo@npm:1.0.0":\r\n  version: 1.0.0\r\n',
  "'__metadata': # berry\n  version: 6\n\"foo@npm:1.0.0\":\n  version: 1.0.0\n",
])('detects Yarn Berry lockfile variant %#', async (contents) => {
  const dir = temporaryDirectory()
  fs.writeFileSync(path.join(dir, 'yarn.lock'), contents)
  const versionsByPackageNames = await readVersionsByPackageNames(dir)
  expect(toSortedArrays(versionsByPackageNames)).toStrictEqual({
    foo: ['1.0.0'],
  })
})

test('extracts target package names for npm: aliases in Yarn v1 and Yarn Berry lockfiles', async () => {
  const classicDir = temporaryDirectory()
  fs.writeFileSync(path.join(classicDir, 'yarn.lock'), `# yarn lockfile v1

"my-alias@npm:minimatch@^3.0.4":
  version "3.0.4"

"scoped-alias@npm:@babel/core@^7.0.0":
  version "7.2.0"

"@my/alias@npm:@pnpm.e2e/foo@^1.0.0":
  version "1.0.0"

"bare-alias@npm:is-positive":
  version "1.0.0"
`)
  expect(toSortedArrays(await readVersionsByPackageNames(classicDir))).toStrictEqual({
    '@babel/core': ['7.2.0'],
    '@pnpm.e2e/foo': ['1.0.0'],
    'is-positive': ['1.0.0'],
    minimatch: ['3.0.4'],
  })

  const berryDir = temporaryDirectory()
  fs.writeFileSync(path.join(berryDir, 'yarn.lock'), `__metadata:
  version: 8

"my-alias@npm:minimatch@^3.0.4":
  version: 3.0.4
  resolution: "minimatch@npm:3.0.4"

"@my/alias@npm:@babel/core@^7.0.0":
  version: 7.2.0
  resolution: "@babel/core@npm:7.2.0"

"bare-alias@npm:is-positive":
  version: 1.0.0
  resolution: "is-positive@npm:1.0.0"

"headless-alias@npm:@pnpm.e2e/foo@^1.0.0":
  version: 1.0.0

"tagged-pkg@npm:latest":
  version: 2.0.0
`)
  expect(toSortedArrays(await readVersionsByPackageNames(berryDir))).toStrictEqual({
    '@babel/core': ['7.2.0'],
    '@pnpm.e2e/foo': ['1.0.0'],
    'is-positive': ['1.0.0'],
    minimatch: ['3.0.4'],
    'tagged-pkg': ['2.0.0'],
  })
})

test('extracts target package names for npm: aliases in package-lock.json v1 and v3', async () => {
  const v1Dir = temporaryDirectory()
  fs.writeFileSync(path.join(v1Dir, 'package-lock.json'), JSON.stringify({
    lockfileVersion: 1,
    dependencies: {
      'my-alias': { version: 'npm:is-positive@1.0.0' },
      parent: {
        version: '1.0.0',
        dependencies: {
          '@my/alias': { version: 'npm:@pnpm.e2e/foo@1.0.0' },
          'self-npm': { version: 'npm:2.0.0' },
        },
      },
    },
  }))
  expect(toSortedArrays(await readVersionsByPackageNames(v1Dir))).toStrictEqual({
    '@pnpm.e2e/foo': ['1.0.0'],
    'is-positive': ['1.0.0'],
    parent: ['1.0.0'],
    'self-npm': ['2.0.0'],
  })

  const v3Dir = temporaryDirectory()
  fs.writeFileSync(path.join(v3Dir, 'package-lock.json'), JSON.stringify({
    lockfileVersion: 3,
    packages: {
      '': {
        name: 'project',
        version: '0.0.0',
        dependencies: {
          'my-alias': 'npm:is-positive@^1.0.0',
          'bare-alias': 'npm:is-negative',
        },
      },
      'node_modules/my-alias': { name: 'is-positive', version: '1.0.0' },
      'node_modules/bare-alias': { name: 'is-negative', version: '2.1.0' },
      'node_modules/parent': {
        version: '1.0.0',
        dependencies: { 'nested-alias': 'npm:@pnpm.e2e/foo@1.0.0' },
      },
      'node_modules/parent/node_modules/@my/nested-alias': {
        name: '@pnpm.e2e/foo',
        version: '1.1.0',
      },
    },
  }))
  expect(toSortedArrays(await readVersionsByPackageNames(v3Dir))).toStrictEqual({
    '@pnpm.e2e/foo': ['1.0.0', '1.1.0'],
    'is-negative': ['2.1.0'],
    'is-positive': ['1.0.0', '^1.0.0'],
    parent: ['1.0.0'],
  })
})

function toSortedArrays (versions: Record<string, Set<string>>): Record<string, string[]> {
  return Object.fromEntries(
    Object.keys(versions)
      .sort()
      .map((name) => [name, Array.from(versions[name]).sort()])
  )
}
