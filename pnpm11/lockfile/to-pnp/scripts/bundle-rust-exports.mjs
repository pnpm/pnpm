import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import esbuild from 'esbuild'

const require = createRequire(import.meta.url)
const yarnDir = path.dirname(require.resolve('@yarnpkg/pnp/package.json'))
const argLicense = fs.readFileSync(path.join(path.dirname(require.resolve('arg')), 'LICENSE.md'), 'utf8')
const result = await esbuild.build({
  entryPoints: [fileURLToPath(new URL('../pnp-runtime/exports.mjs', import.meta.url))],
  alias: {
    'yarn-pnp-exports': path.join(yarnDir, 'lib/node/resolve.js'),
    'yarn-pnp-node-options': path.join(yarnDir, 'lib/loader/node-options.js'),
    arg: require.resolve('arg'),
  },
  bundle: true,
  minify: true,
  platform: 'node',
  format: 'iife',
  globalName: 'pnpmPnpExports',
  banner: { js: `// Generated by pnpm11/lockfile/to-pnp/scripts/bundle-rust-exports.mjs.\n/*\n${argLicense}*/` },
  write: false,
  outfile: fileURLToPath(new URL('../../../../pnpm/crates/deps-restorer/src/pnp_exports.cjs.inc', import.meta.url)),
})
const output = result.outputFiles[0]
if (process.argv.includes('--check')) {
  if (!fs.readFileSync(output.path).equals(output.contents)) {
    throw new Error('The embedded PnP exports resolver is stale. Run pnpm --filter @pnpm/lockfile.to-pnp build:rust-exports.')
  }
} else {
  fs.writeFileSync(output.path, output.contents)
}
