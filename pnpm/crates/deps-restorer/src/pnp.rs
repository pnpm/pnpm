use crate::package_map::{
    PackageMapOptions,
    find_execution_file,
    lockfile_to_package_map,
};
use derive_more::{
    Display,
    Error,
};
use pnpm_lockfile::Lockfile;
use pnpm_package_manifest::PackageManifest;
use std::path::{
    Path,
    PathBuf,
};

pub const PNP_FILENAME: &str = ".pnp.cjs";
const PNP_EXPORTS_RESOLVER: &str = include_str!("pnp_exports.cjs.inc");
const PNP_LOADER_TEMPLATE: &str = include_str!("pnp_loader.cjs.inc");
const PACKAGE_REGISTRY_PLACEHOLDER: &str = "__PNPM_PACKAGE_REGISTRY__";
const MODULES_DIR_PLACEHOLDER: &str = "__PNPM_MODULES_DIR__";

#[derive(Debug, Display, Error)]
pub enum WritePnpFileError {
    #[display("failed to serialize the PnP package registry: {_0}")]
    Serialize(#[error(source)] serde_json::Error),
    #[display("failed to write .pnp.cjs: {_0}")]
    Write(#[error(source)] pnpm_fs::EnsureFileError),
}

pub fn write_pnp_file(
    lockfile: &Lockfile,
    lockfile_dir: &Path,
    config: &pnpm_config::Config,
    layout: &crate::VirtualStoreLayout,
    project_manifests: &[(PathBuf, &PackageManifest)],
) -> Result<(), WritePnpFileError> {
    let package_map = lockfile_to_package_map(
        lockfile,
        &PackageMapOptions {
            lockfile_dir,
            modules_dir: &config.modules_dir,
            package_map_type: pnpm_config::NodePackageMapType::Standard,
            layout,
            project_manifests,
        },
    );
    let registry = serde_json::to_string(&package_map).map_err(WritePnpFileError::Serialize)?;
    let modules_dir = pathdiff::diff_paths(&config.modules_dir, lockfile_dir)
        .unwrap_or_else(|| config.modules_dir.clone());
    let modules_dir = serde_json::to_string(&modules_dir.to_string_lossy())
        .map_err(WritePnpFileError::Serialize)?;
    let contents = render_pnp_loader(&registry, &modules_dir);
    pnpm_fs::ensure_file(&lockfile_dir.join(PNP_FILENAME), contents.as_bytes(), None)
        .map_err(WritePnpFileError::Write)
}

fn render_pnp_loader(registry: &str, modules_dir: &str) -> String {
    let (before_registry, after_registry) = PNP_LOADER_TEMPLATE
        .split_once(PACKAGE_REGISTRY_PLACEHOLDER)
        .expect("embedded PnP loader has a package registry placeholder");
    let (between_values, after_modules_dir) = after_registry
        .split_once(MODULES_DIR_PLACEHOLDER)
        .expect("embedded PnP loader has a modules directory placeholder");
    let mut loader = String::with_capacity(
        PNP_EXPORTS_RESOLVER.len() + PNP_LOADER_TEMPLATE.len() + registry.len() + modules_dir.len(),
    );
    loader.push_str(PNP_EXPORTS_RESOLVER);
    loader.push_str(before_registry);
    loader.push_str(registry);
    loader.push_str(between_values);
    loader.push_str(modules_dir);
    loader.push_str(after_modules_dir);
    loader
}

/// Error type of [`read_pnp_package_dirs`].
#[derive(Debug, Display, Error)]
pub enum ReadPnpFileError {
    #[display("failed to read {path:?}: {error}")]
    Read {
        path: PathBuf,
        #[error(source)]
        error: std::io::Error,
    },
    #[display("{path:?} was generated by pnpm, but its package registry cannot be read")]
    Unreadable { path: PathBuf },
}

/// Larger than any loader pnpm writes, which holds one registry entry per
/// installed package.
const MAX_PNP_FILE_BYTES: usize = 512 * 1024 * 1024;

/// The package directories the `.pnp.cjs` in `lockfile_dir` resolves to, as
/// its loader resolves them. Empty when there is no `.pnp.cjs`, it is not a
/// regular file, or pnpm did not generate it, as with Yarn's.
pub fn read_pnp_package_dirs(lockfile_dir: &Path) -> Result<Vec<PathBuf>, ReadPnpFileError> {
    let path = lockfile_dir.join(PNP_FILENAME);
    let read = |error| ReadPnpFileError::Read { path: path.clone(), error };
    let dir = match pnpm_fs::OpenDir::open(lockfile_dir) {
        Ok(dir) => dir,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(read(error)),
    };
    let Some(bytes) =
        dir.read_child_file_bounded(PNP_FILENAME.as_ref(), MAX_PNP_FILE_BYTES).map_err(read)?
    else {
        return Ok(Vec::new());
    };
    let contents = String::from_utf8_lossy(&bytes);
    if contents.lines().next() != Some(generated_marker()) {
        return Ok(Vec::new());
    }
    package_dirs_of_loader(&contents, lockfile_dir).ok_or(ReadPnpFileError::Unreadable { path })
}

/// The first line of every loader pnpm writes.
fn generated_marker() -> &'static str {
    PNP_EXPORTS_RESOLVER
        .lines()
        .next()
        .unwrap_or(PNP_EXPORTS_RESOLVER)
}

/// Parses the values [`render_pnp_loader`] wrote. Each is single-line JSON,
/// which cannot hold a raw newline, so it ends where its line does.
fn package_dirs_of_loader(contents: &str, lockfile_dir: &Path) -> Option<Vec<PathBuf>> {
    let line_value = |prefix: &str, suffix: &str| {
        contents
            .lines()
            .find_map(|line| line.strip_prefix(prefix)?.strip_suffix(suffix))
    };
    let registry: serde_json::Value =
        serde_json::from_str(line_value("const registry = ", ".packages")?).ok()?;
    let modules_dir: String =
        serde_json::from_str(line_value("const modulesDir = path.resolve(__dirname, ", ")")?).ok()?;
    let modules_dir_url = url::Url::from_directory_path(lockfile_dir.join(modules_dir)).ok()?;
    registry
        .get("packages")?
        .as_object()?
        .values()
        .map(|package| {
            let url = modules_dir_url
                .join(package.get("url")?.as_str()?)
                .ok()?;
            url.to_file_path().ok()
        })
        .collect()
}

#[must_use]
pub fn pnp_path_for_execution(config: &pnpm_config::Config, dir: &Path) -> Option<PathBuf> {
    find_execution_file(config, dir, Path::new(PNP_FILENAME))
}

