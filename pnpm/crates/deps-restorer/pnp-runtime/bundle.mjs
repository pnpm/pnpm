// Bundles exports.mjs and the Yarn PnP resolver it wraps into the script the
// deps-restorer crate embeds. `--check` fails when the embedded copy is stale.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

import esbuild from 'esbuild'

const require = createRequire(import.meta.url)
const yarnDir = path.dirname(require.resolve('@yarnpkg/pnp/package.json'))
const argLicense = fs.readFileSync(path.join(path.dirname(require.resolve('arg')), 'LICENSE.md'), 'utf8')
const result = await esbuild.build({
  entryPoints: [fileURLToPath(new URL('./exports.mjs', import.meta.url))],
  alias: {
    'yarn-pnp-exports': path.join(yarnDir, 'lib/node/resolve.js'),
    'yarn-pnp-node-options': path.join(yarnDir, 'lib/loader/node-options.js'),
    arg: require.resolve('arg'),
  },
  bundle: true,
  minify: true,
  platform: 'node',
  format: 'iife',
  globalName: 'pnpmPnpExports',
  banner: { js: `// Generated by pnpm/crates/deps-restorer/pnp-runtime/bundle.mjs.\n/*\n${argLicense}*/` },
  write: false,
  outfile: fileURLToPath(new URL('../src/pnp_exports.cjs.inc', import.meta.url)),
})
const output = result.outputFiles[0]
if (process.argv.includes('--check')) {
  if (!fs.readFileSync(output.path).equals(output.contents)) {
    throw new Error('The embedded PnP exports resolver is stale. Run pnpm --filter @pnpm-private/pnp-runtime build.')
  }
} else {
  fs.writeFileSync(output.path, output.contents)
}
