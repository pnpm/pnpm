//! `pnpm import` coverage for Yarn classic `__metadata*` package names and
//! `npm:` aliased dependencies across npm and Yarn lockfiles.

use crate::_utils::lockfile_package_keys;

use assert_cmd::prelude::*;
use command_extra::CommandExtra;
use pnpm_testing_utils::bin::{AddMockedRegistry, CommandTempCwd};
use serde_json::json;
use std::{fs, path::Path};

const ALIAS_MANIFEST: &str = r#"{
  "name": "alias-project",
  "version": "0.0.0",
  "dependencies": {
    "foo-alias": "npm:@pnpm.e2e/foo@^1.0.0",
    "@my/bravo-alias": "npm:@pnpm.e2e/bravo-dep@^1.0.0"
  }
}"#;

fn write_file(dir: &Path, relative_path: &str, contents: &str) {
    let path = dir.join(relative_path);
    fs::create_dir_all(path.parent().expect("a file path has a parent"))
        .expect("create parent dir");
    fs::write(path, contents).expect("write fixture file");
}

fn assert_alias_pins(workspace: &Path) {
    let packages = lockfile_package_keys(workspace);
    for expected in ["@pnpm.e2e/foo@1.0.0", "@pnpm.e2e/bravo-dep@1.0.1"] {
        assert!(
            packages.contains(&expected.to_string()),
            "{expected} must be pinned, got {packages:?}",
        );
    }
    for rejected in ["@pnpm.e2e/foo@1.3.0", "@pnpm.e2e/bravo-dep@1.1.0"] {
        assert!(!packages.contains(&rejected.to_string()), "{rejected} must not be pinned");
    }
}

#[test]
fn import_yarn_classic_with_metadata_prefixed_dependencies() {
    let CommandTempCwd {
        pacquet,
        root,
        workspace,
        npmrc_info,
        ..
    } = CommandTempCwd::init().add_mocked_registry();
    let AddMockedRegistry { mock_instance, .. } = npmrc_info;

    let meta_manifest = json!({ "name": "pkg-__metadata", "version": "1.0.0" });
    write_file(&workspace, "meta/package.json", &meta_manifest.to_string());
    let pkg_a_manifest = json!({
        "name": "pkg-a",
        "version": "1.0.0",
        "dependencies": { "pkg-__metadata": "file:../meta" },
    });
    write_file(&workspace, "pkg-a/package.json", &pkg_a_manifest.to_string());
    let app_manifest = json!({
        "name": "my-app",
        "version": "1.0.0",
        "dependencies": {
            "pkg-a": "file:./pkg-a",
            "@pnpm.e2e/foo": "^1.0.0",
        },
    });
    write_file(&workspace, "package.json", &app_manifest.to_string());
    write_file(
        &workspace,
        "yarn.lock",
        r#"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"__metadata-helper@file:../meta":
  version "1.0.0"

"old-pkg@1.0.0":
  version "1.0.0"
  dependencies:
    __metadata-helper "file:../meta"

"pkg-__metadata@file:../meta":
  version "1.0.0"

"pkg-a@file:./pkg-a":
  version "1.0.0"
  dependencies:
    pkg-__metadata "file:../meta"

"@pnpm.e2e/foo@^1.0.0":
  version "1.0.0"
"#,
    );

    pacquet
        .with_arg("import")
        .assert()
        .success();

    let packages = lockfile_package_keys(&workspace);
    assert!(packages.contains(&"@pnpm.e2e/foo@1.0.0".to_string()), "got {packages:?}");
    assert!(!packages.contains(&"@pnpm.e2e/foo@1.3.0".to_string()), "got {packages:?}");

    drop((root, mock_instance));
}

#[test]
fn import_preserves_npm_alias_pins_from_package_lock_v1() {
    let CommandTempCwd {
        pacquet,
        root,
        workspace,
        npmrc_info,
        ..
    } = CommandTempCwd::init().add_mocked_registry();
    let AddMockedRegistry { mock_instance, .. } = npmrc_info;

    write_file(&workspace, "package.json", ALIAS_MANIFEST);
    let lockfile = json!({
        "name": "alias-project",
        "version": "0.0.0",
        "lockfileVersion": 1,
        "dependencies": {
            "foo-alias": { "version": "npm:@pnpm.e2e/foo@1.0.0" },
            "@my/bravo-alias": { "version": "npm:@pnpm.e2e/bravo-dep@1.0.1" },
        },
    });
    write_file(&workspace, "package-lock.json", &lockfile.to_string());

    pacquet
        .with_arg("import")
        .assert()
        .success();
    assert_alias_pins(&workspace);

    drop((root, mock_instance));
}

