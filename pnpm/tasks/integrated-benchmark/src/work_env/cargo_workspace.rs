use pnpm_store_dir::{CafsFileInfo, PackageFilesIndex, StoreDir, StoreIndex};
use pnpm_tarball::ArchiveStoreProjection;
use ssri::{Algorithm, Integrity};
use std::{
    collections::HashMap,
    fmt::Write,
    fs,
    path::Path,
    time::{SystemTime, UNIX_EPOCH},
};

pub(super) const CRATE_COUNT: usize = 800;
const CRATE_VERSION: &str = "1.0.0";
const MODULE_COUNT: usize = 3;

pub(super) fn root_manifest() -> String {
    serde_json::json!({
        "name": "cargo-benchmark-root",
        "version": "0.1.0",
        "private": true,
    })
    .to_string()
}

pub(super) fn create_project(root: &Path) {
    let src_dir = root.join("src");
    fs::create_dir_all(&src_dir).expect("create cargo workspace src directory");
    fs::write(
        root.join("Cargo.toml"),
        format!(
            "[package]\nname = \"cargo-benchmark-root\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n\
             [workspace]\n\n\
             [dependencies]\n{} = \"{CRATE_VERSION}\"\n",
            crate_name(0),
        ),
    )
    .expect("write root Cargo.toml");
    fs::write(src_dir.join("lib.rs"), "pub fn root() {}\n").expect("write root src/lib.rs");
    fs::write(root.join("Cargo.lock"), cargo_lock_contents()).expect("write Cargo.lock");
}

pub(super) fn seed_store(root: &Path) {
    let store_dir = StoreDir::new(root.join("store-dir"));
    let entries: Vec<(String, PackageFilesIndex)> =
        (0..CRATE_COUNT).map(|index| seed_crate(&store_dir, index)).collect();
    let mut store_index =
        StoreIndex::open_in(&store_dir).expect("open store index for cargo benchmark");
    store_index.set_many(entries).expect("insert cargo benchmark store index entries");
}

pub(super) fn verify_materialized_crates(root: &Path) {
    let crates_io_dir = root.join(".pnpm/crates/crates-io");
    for index in 0..CRATE_COUNT {
        let name = crate_name(index);
        let link = crates_io_dir.join(format!("{name}-{CRATE_VERSION}"));
        assert!(
            link.join(".cargo-checksum.json").is_file(),
            "expected prewarm to materialize crate slot at {}",
            link.display(),
        );
    }
}

fn seed_crate(store_dir: &StoreDir, index: usize) -> (String, PackageFilesIndex) {
    let name = crate_name(index);
    let checksum = crate_checksum(index);
    let integrity = Integrity::from_hex(&checksum, Algorithm::Sha256)
        .expect("build crate integrity")
        .to_string();
    let key = ArchiveStoreProjection::RawArchive.store_index_key(
        &integrity,
        &format!("crate:{name}@{CRATE_VERSION}"),
    );
    let mut files = HashMap::with_capacity(MODULE_COUNT + 2);
    let mut cargo_toml = format!(
        "[package]\nname = \"{name}\"\nversion = \"{CRATE_VERSION}\"\nedition = \"2021\"\n",
    );
    if index + 1 < CRATE_COUNT {
        writeln!(cargo_toml, "\n[dependencies]\n{} = \"{CRATE_VERSION}\"", crate_name(index + 1))
            .expect("format crate Cargo.toml dependency");
    }
    files.insert("Cargo.toml".to_string(), write_cas_blob(store_dir, cargo_toml.as_bytes()));
    files.insert(
        "src/lib.rs".to_string(),
        write_cas_blob(store_dir, format!("pub const CRATE_INDEX: usize = {index};\n").as_bytes()),
    );
    for module in 0..MODULE_COUNT {
        files.insert(
            format!("src/module_{module}.rs"),
            write_cas_blob(
                store_dir,
                format!("pub const MODULE_{module}: usize = {index};\n").as_bytes(),
            ),
        );
    }
    (key, PackageFilesIndex { algo: "sha512".to_string(), files, ..PackageFilesIndex::default() })
}

fn write_cas_blob(store_dir: &StoreDir, contents: &[u8]) -> CafsFileInfo {
    let (_, file_hash) =
        store_dir.write_cas_file(contents, false).expect("write cas file for cargo benchmark");
    let checked_at = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system clock after unix epoch")
        .as_millis() as u64;
    CafsFileInfo {
        digest: format!("{file_hash:x}"),
        mode: 0o644,
        size: contents.len() as u64,
        checked_at: Some(checked_at),
    }
}

fn cargo_lock_contents() -> String {
    let mut lockfile = format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n\
         version = 3\n\n[[package]]\nname = \"cargo-benchmark-root\"\nversion = \"0.1.0\"\n\
         dependencies = [\n \"{}\",\n]\n",
        crate_name(0),
    );
    for index in 0..CRATE_COUNT {
        writeln!(
            lockfile,
            "\n[[package]]\nname = \"{}\"\nversion = \"{CRATE_VERSION}\"\n\
             source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
             checksum = \"{}\"",
            crate_name(index),
            crate_checksum(index),
        )
        .expect("format Cargo.lock package entry");
        if index + 1 < CRATE_COUNT {
            writeln!(lockfile, "dependencies = [\n \"{}\",\n]", crate_name(index + 1)).expect(
                "format Cargo.lock package dependencies",
            );
        }
    }
    lockfile
}

fn crate_name(index: usize) -> String {
    format!("benchmark-crate-{index:04}")
}

fn crate_checksum(index: usize) -> String {
    format!("{:064x}", index + 1)
}
